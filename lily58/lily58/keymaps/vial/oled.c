static bool     luna_jump_requested = false; // set on the right half by RPC
static bool     luna_in_air         = false;
static uint32_t luna_jump_timer     = 0;

static void luna_clear_line(uint8_t line) {
    for (uint8_t x = 0; x < LUNA_WIDTH; x++) {
        oled_write_raw_byte(0, line * LUNA_WIDTH + x);
    }
}

static void render_luna(void) {
    bool redraw = timer_elapsed32(anim_timer) >= ANIM_FRAME_DURATION;
    if (luna_jump_requested) {
        luna_jump_requested = false;
        luna_in_air         = true;
        luna_jump_timer     = timer_read32();
        redraw              = true;
    } else if (luna_in_air && timer_elapsed32(luna_jump_timer) >= LUNA_JUMP_DURATION) {
        luna_in_air = false;
        redraw      = true;
    }
    if (!redraw) {
        return;
    }
    if (timer_elapsed32(anim_timer) >= ANIM_FRAME_DURATION) {
        anim_timer    = timer_read32();
        current_frame = (current_frame + 1) % 2;
    }

    // RAISE / ADJUST (or Caps Lock): bark. LOWER or Shift: sneak. Else by WPM.
    uint8_t layer = get_highest_layer(layer_state);
    uint8_t wpm   = get_current_wpm();
    const char (*frame)[LUNA_WIDTH];
    if (layer == 2 || layer == 3 || host_keyboard_led_state().caps_lock) {
        frame = luna_bark[current_frame];
    } else if (layer == 1 || (get_mods() & MOD_MASK_SHIFT)) {
        frame = luna_sneak[current_frame];
    } else if (wpm <= LUNA_MIN_WALK_SPEED) {
        frame = luna_sit[current_frame];
    } else if (wpm <= LUNA_MIN_RUN_SPEED) {
        frame = luna_walk[current_frame];
    } else {
        frame = luna_run[current_frame];
    }

    uint8_t top = luna_in_air ? LUNA_LINE - 1 : LUNA_LINE;
    luna_clear_line(luna_in_air ? LUNA_LINE + 2 : LUNA_LINE - 1);
    oled_set_cursor(0, top);
    oled_write_raw_P(frame[0], LUNA_WIDTH * 3);
}

static void render_wpm(void) {
    // Portrait: 5 characters per line.
    oled_set_cursor(0, 6);
    oled_write_P(PSTR(" WPM "), false);
    oled_set_cursor(0, 7);
    oled_write_P(PSTR(" "), false);
    oled_write(get_u8_str(get_current_wpm(), ' '), false);
    oled_write_P(PSTR(" "), false);
}

// Space is handled on the left (master) half; tell the right half to jump.
static bool luna_jump_to_send = false;

static void luna_jump_rpc(uint8_t in_len, const void *in_data, uint8_t out_len, void *out_data) {
    luna_jump_requested = true;
}

void keyboard_post_init_user(void) {
    transaction_register_rpc(USER_SYNC_LUNA_JUMP, luna_jump_rpc);
}

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    // Plain Space, or a mod-tap whose tap is Space (e.g. RGUI_T(KC_SPC)) when tapped.
    bool is_space = keycode == KC_SPC ||
                    (IS_QK_MOD_TAP(keycode) && QK_MOD_TAP_GET_TAP_KEYCODE(keycode) == KC_SPC && record->tap.count > 0);
    if (is_space && record->event.pressed) {
        luna_jump_to_send = true;
    }
    return true;
}

// Safety net against stuck modifiers (e.g. Ctrl staying on after Ctrl+Space):
// a held modifier needs a held key, so if mods stay registered while no key
// in either half is physically down, clear them.
#define STUCK_MODS_TIMEOUT 300
static bool any_key_down(void) {
    for (uint8_t row = 0; row < MATRIX_ROWS; row++) {
        if (matrix_get_row(row)) {
            return true;
        }
    }
    return false;
}

static void clear_stuck_mods(void) {
    static bool     waiting = false;
    static uint32_t since   = 0;
    if (get_mods() == 0 || any_key_down()) {
        waiting = false;
        return;
    }
    if (!waiting) {
        waiting = true;
        since   = timer_read32();
    } else if (timer_elapsed32(since) > STUCK_MODS_TIMEOUT) {
        waiting = false;
        clear_mods();
        send_keyboard_report();
    }
}

void housekeeping_task_user(void) {
    if (!is_keyboard_master()) {
        return;
    }
    clear_stuck_mods();
    if (luna_jump_to_send) {
        luna_jump_to_send = false;
        transaction_rpc_send(USER_SYNC_LUNA_JUMP, 0, NULL);
    }
}

bool oled_task_user(void) {
    if (is_keyboard_master()) {
        render_logo();
        render_space();
        render_layer_state();
        render_space();
        render_mod_status_gui_alt(get_mods());
        render_mod_status_ctrl_shift(get_mods());
    }else{
        // Luna redraws every frame, which keeps waking the OLED
        // and defeats OLED_TIMEOUT. Sleep explicitly when the keyboard is idle.
        if (last_input_activity_elapsed() > OLED_TIMEOUT) {
            oled_off();
            return false;
        }
        render_luna();
        render_wpm();
    }

    return false;

}

